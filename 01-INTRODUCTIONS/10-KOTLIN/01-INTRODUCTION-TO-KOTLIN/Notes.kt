/*
WHAT IS KOTLIN?

Kotlin is a modern programming language created by JetBrains.

It is designed to be:

- Easy to read.
- Safe.
- Concise.
- Interoperable with Java.
- Productive.

Kotlin helps developers write less code while reducing common programming mistakes.
*/

/*
HISTORY OF KOTLIN

2011:
JetBrains announced Kotlin.

2012:
Kotlin became open source.

2016:
Kotlin 1.0 was officially released.

2017:
Google announced official support for Kotlin on Android.

2019:
Google declared Kotlin the preferred language for Android development.
*/

/*
WHY WAS KOTLIN CREATED?

JetBrains wanted a language that:

- Reduced boilerplate code.
- Improved developer productivity.
- Worked with existing Java code.
- Prevented common bugs.
- Was pleasant to use.
*/

/*
WHERE IS KOTLIN USED?

1. Android Development
2. Backend Development
3. Desktop Applications
4. Web Development
5. Multiplatform Projects
6. Command-Line Tools
*/

/*
KOTLIN VS JAVA

Kotlin:
- Less code.
- Built-in Null Safety.
- More modern syntax.

Java:
- More verbose.
- Older ecosystem.
- Extremely popular.
*/

/*
KOTLIN VS C#

Kotlin:
- Runs mainly on the JVM.
- Created by JetBrains.

C#:
- Runs mainly on .NET.
- Created by Microsoft.

Both languages:
- Support OOP.
- Are statically typed.
- Have modern features.
*/

/*
THE FIRST KOTLIN PROGRAM

fun main() {
    println("Hello, World!")
}

This is the most famous beginner program.
*/

/*
BREAKING DOWN THE PROGRAM

fun
→ Defines a function.

main()
→ The entry point of the program.

println()
→ Displays text on the console.

"Hello, World!"
→ The message shown to the user.
*/

/*
HOW KOTLIN EXECUTES

Kotlin Code (.kt)
        ↓
Kotlin Compiler
        ↓
JVM Bytecode (.class)
        ↓
Java Virtual Machine
        ↓
Program Output
*/

/*
COMMON BEGINNER MISTAKES

1. Misspelling println()

Wrong:
prntln("Hello")

Correct:
println("Hello")

---------------------------------

2. Missing Parentheses

Wrong:
println "Hello"

Correct:
println("Hello")

---------------------------------

3. Extra Braces

Wrong:
fun main() {
    println("Hello")
}}

Correct:
fun main() {
    println("Hello")
}
*/

