    /*
     * ==========================================================
     * 08 - ALGORITHMS
     * ==========================================================
     *
     * WHAT IS AN ALGORITHM?
     *
     * An algorithm is a sequence of step-by-step instructions
     * used to solve a problem or perform a task.
     *
     * Examples from everyday life:
     *
     * Making a sandwich:
     * 1. Get bread.
     * 2. Add ingredients.
     * 3. Close the sandwich.
     * 4. Eat it.
     *
     * Following a recipe:
     * 1. Gather ingredients.
     * 2. Mix them.
     * 3. Cook.
     * 4. Serve.
     *
     * Programming works the same way.
     * We give the computer a list of instructions to follow.
     *
     * ==========================================================
     * CHARACTERISTICS OF AN ALGORITHM
     * ==========================================================
     *
     * 1. It has a beginning and an end.
     * 2. Its steps are clear and precise.
     * 3. It solves a specific problem.
     * 4. It produces an output or result.
     * 5. It finishes after a finite number of steps.
     *
     * ==========================================================
     * PSEUDOCODE
     * ==========================================================
     *
     * Pseudocode is an informal way of describing algorithms
     * using simple language before writing actual code.
     *
     * Example:
     *
     * Start
     * Ask the user for two numbers
     * Add the numbers
     * Display the result
     * End
     *
     * ==========================================================
     * WHY ARE ALGORITHMS IMPORTANT?
     * ==========================================================
     *
     * - They help solve problems.
     * - They organize our thinking.
     * - They improve efficiency.
     * - Every computer program uses algorithms.
